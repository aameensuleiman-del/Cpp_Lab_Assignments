#include <iostream>
using namespace std;
int main()
{
    //Task 2: Program demonstrating 5 different data types.
    // 1. int (integer)
    int age = 19;

    // 2. double (double-precision floating-point)
    double gpa = 3.35;

    // 3. char (single character)
    char grade = 'B';

    // 4. bool (boolean: true or false)
    bool isEnrolled = true;

    // 5. string (text sequence)
    string courseTitle = "Programming Fundamentals";

    cout << "Age: " << age << endl;
    cout << "GPA: " << gpa << endl;
    cout << "Grade: " << grade << endl;
    cout << "Enrolled: " << isEnrolled << endl;
    cout << "Course: " << courseTitle << endl;

    return 0;
}
